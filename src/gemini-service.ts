import { GoogleGenerativeAI } from '@google/generative-ai';
import { ProjectInfo } from './types';

export class GeminiService {
  private genAI: GoogleGenerativeAI;
  private model: any;

  constructor(apiKey: string) {
    this.genAI = new GoogleGenerativeAI(apiKey);
    this.model = this.genAI.getGenerativeModel({ model: 'gemini-2.5-flash' });
  }

  async generateReadme(projectInfo: ProjectInfo, sampleCode: string): Promise<string> {
    const prompt = this.buildPrompt(projectInfo, sampleCode);

    try {
      const result = await this.model.generateContent(prompt);
      const response = await result.response;
      return response.text();
    } catch (error: any) {
  console.error("Gemini Error:", error);
  console.error("Message:", error?.message);
  console.error("Status:", error?.status);
  console.error("Stack:", error?.stack);

  throw error;
}
  }

private buildPrompt(projectInfo: ProjectInfo, sampleCode: string): string {
  return `
# ROLE

You are a senior technical writer and open-source maintainer.

Your task is to generate a production-quality README.md for a GitHub repository by analyzing the provided project metadata, folder structure, dependencies, and source code.

Write as if this README will be the first thing developers see when visiting the repository.

---

# PROJECT INFORMATION

## Name
${projectInfo.name}

## Type
${projectInfo.type}

## Languages
${projectInfo.languages.join(", ")}

## Dependencies
${projectInfo.dependencies.slice(0, 20).join(", ")}

---

# PROJECT STRUCTURE

${projectInfo.structure}

---

# SAMPLE SOURCE CODE

${sampleCode.slice(0, 3000)}

---

# WRITING PRINCIPLES

- Infer the project's purpose from the available information.
- Never invent features that are not supported by the code.
- If something cannot be confidently determined, omit it instead of guessing.
- Write in a professional, concise, and developer-focused tone.
- Avoid marketing language and exaggerated claims.
- Prefer practical explanations over generic descriptions.
- Use clean Markdown.
- Keep sections consistent and well organized.
- Use emojis only where they genuinely improve readability.

---

# REQUIRED README STRUCTURE

Generate the README in the following order.

# Project Title

One short paragraph explaining:
- what the project is
- who it is for
- what problem it solves

---

## Features

List the major capabilities discovered from the codebase.

Only include features that can reasonably be inferred.

---

## Tech Stack

Group technologies into categories when possible.

Example:

- Frontend
- Backend
- Database
- Styling
- AI
- Tooling

---

## Installation

Provide installation commands using fenced bash code blocks.

Include:

- cloning
- installing dependencies
- starting development
- production build if applicable

---

## Usage

Explain how to run and use the project.

Include commands whenever appropriate.

---

## Project Structure

Briefly explain the purpose of important folders and files instead of simply repeating the directory tree.

---

## Configuration

List environment variables or configuration requirements only if they appear to exist.

Use a Markdown table.

Example:

| Variable | Description |
|----------|-------------|

---

## Contributing

Provide concise contribution guidelines suitable for an open-source repository.

---

## License

If no license can be determined, write:

"This project does not currently specify a license."

---

# STYLE

- Use GitHub-flavored Markdown.
- Use proper headings.
- Use fenced code blocks.
- Use tables where appropriate.
- Keep paragraphs short.
- Prefer bullet lists over long prose.
- Avoid repetition.
- Avoid filler text.
- Do not include placeholder content like "Lorem ipsum".
- Do not mention that this README was generated by AI.

---

Return ONLY the README.md.
`;
}}
